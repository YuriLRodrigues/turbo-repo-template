// @ts-check
import nextVitals from 'eslint-config-next/core-web-vitals'
import nextTs from 'eslint-config-next/typescript'
import importHelpers from 'eslint-plugin-import-helpers'
import preferArrowFunctions from 'eslint-plugin-prefer-arrow-functions'
import prettierRecommended from 'eslint-plugin-prettier/recommended'

/*
 * `no-restricted-syntax` selectors. Flat config does not merge rule options, so every override that sets the rule
 * again has to list the ones it keeps: they are exported one by one for that.
 */

export const noDefaultExport = {
  selector: 'ExportDefaultDeclaration',
  message:
    'Use a named export (export const X = ...). A default export is only for App Router files (page, layout, template, error, not-found, manifest) and config files.',
}

// Scrolling boxes are always a ScrollArea (docs/patterns/web/scroll-area.md): its scrollbar only shows while scrolling,
// it is keyboard reachable and it is named for screen readers.
const RAW_OVERFLOW = String.raw`\boverflow-(?:[xy]-)?(?:auto|scroll)\b`
const rawOverflowMessage =
  'Use <ScrollArea> from @workspace/ui/components/scroll-area instead of a raw overflow-auto/scroll class.'

export const noRawOverflow = [
  { selector: `Literal[value=/${RAW_OVERFLOW}/]`, message: rawOverflowMessage },
  { selector: `TemplateElement[value.raw=/${RAW_OVERFLOW}/]`, message: rawOverflowMessage },
]

// apps/web is a static export (docs/patterns/web/static-export.md): there is no Next server at runtime.
export const noUseServer = {
  selector: "ExpressionStatement[directive='use server']",
  message: 'No Server Actions: the web app is a static export. Call the API through @workspace/api-client.',
}

export const noUseActionState = {
  selector: "ImportSpecifier[imported.name='useActionState']",
  message: 'Forms use useAppForm + a TanStack Query mutation, not useActionState.',
}

/** The selectors every React workspace starts from. */
export const baseRestrictedSyntax = [noDefaultExport, ...noRawOverflow, noUseServer, noUseActionState]

/** Files that export a default by convention. */
export const defaultExportFiles = [
  '**/app/**/{page,layout,loading,error,global-error,not-found,template,default,manifest}.{ts,tsx}',
  '*.config.{js,mjs,ts,mts}',
  '**/*.config.{js,mjs,ts,mts}',
]

/**
 * ESLint for the React workspaces: the Next.js app (apps/web) and the libraries it consumes (packages/ui,
 * packages/api-client). Spread it into `defineConfig([...])` and add the workspace's own overrides after it.
 *
 * @param {{ tsconfigRootDir: string, next?: boolean }} options `next: false` for a library (no pages to check).
 * @returns {import('eslint').Linter.Config[]}
 */
export const reactConfig = ({ tsconfigRootDir, next = true }) => [
  ...nextVitals,
  ...nextTs,
  {
    ignores: [
      '.next/**',
      'out/**',
      'dist/**',
      'coverage/**',
      'next-env.d.ts',
      'playwright-report/**',
      'test-results/**',
      // Generated by Orval: never edited, never linted.
      'src/gen/**',
    ],
  },

  // 1. The base rules of the project.
  {
    plugins: {
      'import-helpers': importHelpers,
      'prefer-arrow-functions': preferArrowFunctions,
    },
    rules: {
      'no-console': 'warn',
      '@typescript-eslint/no-explicit-any': 'error',
      '@typescript-eslint/consistent-type-imports': ['error', { fixStyle: 'inline-type-imports' }],
      '@typescript-eslint/no-unused-vars': ['error', { argsIgnorePattern: '^_', varsIgnorePattern: '^_' }],

      // Components, hooks and helpers are arrow functions in a const. Auto-fixable with `npm run lint`.
      'prefer-arrow-functions/prefer-arrow-functions': ['error', { returnStyle: 'unchanged' }],
      'prefer-arrow-callback': 'error',

      'no-restricted-syntax': ['error', ...baseRestrictedSyntax],

      'import-helpers/order-imports': [
        'warn',
        {
          newlinesBetween: 'always',
          groups: [
            ['/^react(-dom)?(\\/|$)/'],
            ['/^next(\\/|$)/'],
            'module',
            '/^@workspace\\//',
            '/^@\\//',
            ['parent', 'sibling', 'index'],
          ],
          alphabetize: { order: 'asc', ignoreCase: true },
        },
      ],

      ...(next ? {} : { '@next/next/no-html-link-for-pages': 'off', '@next/next/no-img-element': 'off' }),
    },
  },

  // 2. Type-aware: a promise that nobody awaits swallows its error.
  {
    files: ['**/*.{ts,tsx,mts}'],
    languageOptions: {
      parserOptions: {
        projectService: true,
        tsconfigRootDir,
      },
    },
    rules: {
      '@typescript-eslint/no-floating-promises': 'error',
    },
  },

  // 3. App Router conventions and config files are the only places with a default export.
  {
    files: defaultExportFiles,
    rules: {
      'no-restricted-syntax': ['error', ...noRawOverflow, noUseServer, noUseActionState],
      'import/no-anonymous-default-export': 'off',
    },
  },

  // 4. Terminal scripts: the console is the output.
  {
    files: ['tooling/**', 'test/e2e/fake-api/**'],
    rules: {
      'no-console': 'off',
    },
  },

  // Prettier last: it turns off the formatting rules and reports its own differences as lint errors.
  prettierRecommended,
]
